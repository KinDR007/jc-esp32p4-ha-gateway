"""Writes the catalog of all YAMNet classes grouped by the AudioSet ontology.

  docs/sound-classes.md                                   human readable list
  firmware/gateway/components/sound/sound_classes.json    index, name, group path (for the web UI)

The class names and the ontology are from AudioSet (CC BY-SA 4.0, research.google.com/audioset).

    .venv/bin/python gen_class_catalog.py
"""
import collections
import csv
import json
import os
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
ONTOLOGY_URL = 'https://raw.githubusercontent.com/audioset/ontology/master/ontology.json'


def load():
    path = os.path.join(HERE, 'data', 'ontology.json')
    if not os.path.exists(path):
        urllib.request.urlretrieve(ONTOLOGY_URL, path)
    onto = {n['id']: n for n in json.load(open(path))}
    parents = collections.defaultdict(list)
    for n in onto.values():
        for c in n['child_ids']:
            parents[c].append(n['id'])
    classes = []
    for row in csv.DictReader(open(os.path.join(HERE, 'data', 'yamnet_class_map.csv'))):
        chain = [row['mid']]
        while parents.get(chain[-1]):
            chain.append(parents[chain[-1]][0])
        names = [onto[m]['name'] for m in reversed(chain)]
        top = names[0]
        sub = names[1] if len(names) > 2 else (names[1] if len(names) == 2 and names[1] != row['display_name'] else '-')
        classes.append({'index': int(row['index']), 'name': row['display_name'], 'top': top, 'group': sub})
    return classes


def main():
    classes = load()
    out = os.path.join(ROOT, 'firmware', 'gateway', 'components', 'sound', 'sound_classes.json')
    with open(out, 'w') as f:
        json.dump([[c['index'], c['name'], c['top'], c['group']] for c in classes], f, separators=(',', ':'))

    by_top = collections.defaultdict(lambda: collections.defaultdict(list))
    for c in classes:
        by_top[c['top']][c['group']].append(c)
    lines = ['# Detectable sounds (YAMNet, 521 classes)', '',
             'Generated by `tools/yamnet/gen_class_catalog.py`. Groups follow the AudioSet ontology; a class',
             'appears under its first parent. Class names and ontology: AudioSet, CC BY-SA 4.0.', '',
             '| Category | Classes |', '|---|---|']
    for top, groups in sorted(by_top.items(), key=lambda kv: -sum(len(v) for v in kv[1].values())):
        lines.append(f'| {top} | {sum(len(v) for v in groups.values())} |')
    for top, groups in sorted(by_top.items(), key=lambda kv: -sum(len(v) for v in kv[1].values())):
        lines += ['', f'## {top}', '']
        for group, items in sorted(groups.items()):
            names = ', '.join(f'{c["name"]} ({c["index"]})' for c in items)
            lines.append(f'- **{group}** ({len(items)}): {names}' if group != '-' else f'- {names}')
    with open(os.path.join(ROOT, 'docs', 'sound-classes.md'), 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'{len(classes)} classes -> docs/sound-classes.md, {os.path.relpath(out, ROOT)}')


if __name__ == '__main__':
    main()
