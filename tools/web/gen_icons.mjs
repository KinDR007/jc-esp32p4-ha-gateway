// Embeds the Material Design Icons used by the web UI as SVG paths (no font, no network access).
// Icons are found in firmware/gateway/web/index.html in ic(...) and h3('name', ...) calls and `icon: 'name'` fields;
// the block between the ICONS markers is rewritten. MDI: Pictogrammers, Apache-2.0.
//
//   npm --prefix tools/web ci && node tools/web/gen_icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import * as mdi from '@mdi/js';

const page = new URL('../../firmware/gateway/web/index.html', import.meta.url);
const html = readFileSync(page, 'utf8');
const begin = '/* ICONS:BEGIN */', end = '/* ICONS:END */';
const [head, rest] = html.split(begin);
if (rest === undefined || !rest.includes(end)) throw new Error('ICONS markers not found');
const tail = rest.slice(rest.indexOf(end));

const names = new Set();
// every quoted name inside ic(...) or the first argument of h3(...), and `icon: '...'` fields
for (const m of (head + tail).matchAll(/\bic\(([^)]*)\)/g)) for (const q of m[1].matchAll(/'([a-z0-9-]+)'/g)) names.add(q[1]);
for (const m of (head + tail).matchAll(/\bh3\('([a-z0-9-]+)'|\bicon: '([a-z0-9-]+)'/g)) names.add(m[1] || m[2]);
const key = n => 'mdi' + n.split('-').map(p => p[0].toUpperCase() + p.slice(1)).join('');
const missing = [...names].filter(n => !mdi[key(n)]);
if (missing.length) throw new Error('unknown icons: ' + missing.join(', '));

const block = `${begin}\n// Generated by tools/web/gen_icons.mjs from @mdi/js 7.4.47 (Apache-2.0), do not edit.\nconst ICONS = {\n` +
  [...names].sort().map(n => `  '${n}': '${mdi[key(n)]}',`).join('\n') + '\n};\n';
writeFileSync(page, head + block + tail);
console.log(`${names.size} icons`);
